def normalize_language(language: str | None) -> str:
    return language if language in SUPPORTED_LANGUAGES else "ro"


def translate(key: str, language: str = "ro", **values) -> str:
    language = normalize_language(language)
    entry = TRANSLATIONS.get(key)
    if entry is None:
        return key
    text = entry.get(language) or entry["ro"]
    return text.format(**values) if values else text
